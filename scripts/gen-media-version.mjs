/**
 * Writes `lib/media-version.ts` with a short content hash of the hero media.
 *
 * Files under `public/` keep a stable URL forever (unlike `/_next/static/*`,
 * which Next fingerprints), so when `hero.mp4` is replaced a browser that has
 * the old clip cached plays it for a beat on reload before revalidation swaps
 * in the new bytes. Stamping the URL with a content hash gives each version its
 * own cache key, which kills the flash — and makes it safe to serve the media
 * `immutable` (see `public/_headers`).
 *
 * Runs from `prebuild`/`predev`, so the stamp is always in step with the file.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const hashOf = (rel) =>
  createHash("sha256")
    .update(readFileSync(path.join(root, "public", rel)))
    .digest("hex")
    .slice(0, 8);

const version = hashOf("hero.mp4") + hashOf("hero-poster.jpg");

writeFileSync(
  path.join(root, "lib", "media-version.ts"),
  `// GENERATED by scripts/gen-media-version.mjs — do not edit by hand.\n` +
    `// Content hash of the hero media, appended to its URLs so a replaced file\n` +
    `// never collides with a cached copy of the old one.\n` +
    `export const heroMediaVersion = "${version}";\n`,
  "utf8",
);

console.log(`media-version: ${version}`);
